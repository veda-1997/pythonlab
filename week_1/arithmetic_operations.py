# Taking input as strings and converting them to integers
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print("Sum:", a + b)
print("Difference:", a - b)
print("Product:", a * b)
print("Quotient:", a / b)

# Output:
# Enter first number: 20
# Enter second number: 5
# Sum: 25
# Difference: 15
# Product: 100
# Quotient: 4.0
