name = "Veda"
marks = 95

# Method 1: Comma-separated print()
print("Name:", name, "Marks:", marks)

# Method 2: str.format()
print("Name: {}, Marks: {}".format(name, marks))

# Method 3: f-string
print(f"Name: {name}, Marks: {marks}")

# Output:
# Name: Veda Marks: 95
# Name: Veda, Marks: 95
# Name: Veda, Marks: 95
