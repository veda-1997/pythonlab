# Assign different values to three variables in one line
a, b, c = 10, 20, 30

print("a =", a)
print("b =", b)
print("c =", c)

# Assign the same value to all three variables
a = b = c = 100

print("After assigning 100:")
print("a =", a)
print("b =", b)
print("c =", c)

# Output:
# a = 10
# b = 20
# c = 30
# After assigning 100:
# a = 100
# b = 100
# c = 100
