def student_info(name, roll_no, branch):
    print("Name:", name)
    print("Roll No:", roll_no)
    print("Branch:", branch)

student_info("Veda", "25341a05m9", "CSE")

student_info(branch="CSE", name="Veda", roll_no="25341a05m9")

# Output:
# Name: Veda
# Roll No: 25341a05m9
# Branch: CSE
# Name: Veda
# Roll No: 25341a05m9
# Branch: CSE
